#!/usr/bin/env python3
"""Generate portable category/type references from a pinned, public MISP metadata snapshot."""
import argparse
import csv
import io
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'categories-and-types/reference/attribute-definitions.json'
QMD = ROOT / 'categories-and-types/_reference.qmd'
CSV = ROOT / 'categories-and-types/reference/attribute-types.csv'


def md(value):
    return re.sub(r'([\\`*_[\]<>|])', r'\\\1', str(value)).replace('\n', ' ')


def render(data):
    types, categories = data['types'], data['categories']
    assert len(types) == len(set(types)) and types and categories
    for name, definition in types.items():
        assert definition['default_category'] in categories, name
        assert name in categories[definition['default_category']]['types'], name
        assert definition['to_ids'] in (0, 1), name
    assert all(set(category['types']) <= set(types) for category in categories.values())
    qmd = ['<!-- Generated by assets/data-model/generate_reference.py; edit the snapshot, not these rows. -->',
           '', '## Categories {#categories}', '',
           'Each entry lists the accepted attribute types, not just their default category. '
           'Use the category filter in the type reference to find the same allowed combinations.', '',
           '::: {.misp-category-reference}', '']
    for name, definition in sorted(categories.items(), key=lambda item: item[0].casefold()):
        accepted = ', '.join('`' + t + '`' for t in sorted(definition['types'], key=str.casefold))
        qmd += ['**' + md(name) + '**', ': ' + md(definition['desc']), '',
                '  **Accepted types (' + str(len(definition['types'])) + '):** ' + accepted + '.', '']
    qmd += [':::', '', '## Types {#types}', '',
            'Search the HTML reference or narrow it by **any allowed category** and the model\'s '
            '**IDS default**. These are model defaults; templates, importers and explicit input can '
            'choose different flags. Review the saved observation before using it for detection.', '',
            'Without JavaScript, all rows remain visible. PDF/ePub include the complete reference. '
            'Browser printing includes all rows even when a screen filter is active.', '',
            '::: {.misp-reference-table data-table-label="MISP 3.0 attribute type reference"}', '',
            '| Attribute type | Defaults | Description |', '|---|---|---|']
    output = io.StringIO(newline='')
    writer = csv.writer(output, lineterminator='\n')
    writer.writerow(['Attribute type', 'Default category', 'IDS default', 'Allowed categories', 'Description'])
    for name, definition in sorted(types.items(), key=lambda item: item[0].casefold()):
        allowed = sorted((c for c, d in categories.items() if name in d['types']), key=str.casefold)
        assert all(';' not in c and '"' not in c for c in allowed)
        code = '[' + md(name) + ']'
        attrs = '{.misp-type data-categories="' + ';'.join(allowed) + '" data-default-ids="' + str(definition['to_ids']) + '"}'
        defaults = md(definition['default_category']) + ' · IDS ' + ('on' if definition['to_ids'] else 'off')
        qmd.append('| ' + code + attrs + ' | ' + defaults + ' | ' + md(definition['desc']) + ' |')
        writer.writerow([name, definition['default_category'], definition['to_ids'], '; '.join(allowed), definition['desc'].strip()])
    qmd += ['', ':::', '']
    return '\n'.join(qmd), output.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check committed outputs without writing files')
    args = parser.parse_args()
    outputs = zip((QMD, CSV), render(json.loads(SOURCE.read_text())))
    for path, content in outputs:
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Reference needs regeneration: ' + str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    print('Reference verified.' if args.check else 'Reference generated.')


if __name__ == '__main__':
    main()
